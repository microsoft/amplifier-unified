import {spawn} from 'node:child_process';
import {createServer} from 'vite';
import {chromium,expect} from '@playwright/test';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';

const root=fileURLToPath(new URL('../../',import.meta.url));
const fixture=spawn(process.env.AMPLIFIER_TEST_PYTHON||root+'.venv/bin/python',['-u',root+'tests/fixtures/browser_detail_server.py',root],{stdio:['ignore','pipe','inherit']});
let browser,vite;const errors=[],calls=[];
try{
 const ready=await new Promise((resolve,reject)=>{let output='';const timer=setTimeout(()=>reject(Error('Fixture timeout')),20000);fixture.once('exit',code=>{clearTimeout(timer);reject(Error('Fixture exit '+code))});fixture.stdout.on('data',chunk=>{output+=chunk;for(const line of output.split('\n'))try{const value=JSON.parse(line);if(value.port){clearTimeout(timer);resolve(value)}}catch{}})});
 const target=`http://127.0.0.1:${ready.port}`,headers={Authorization:'Bearer fixture-detail-token','content-type':'application/json'};
 const control=async body=>{const response=await fetch(target+'/api/fixture/control',{method:'POST',headers,body:JSON.stringify(body)});assert.equal(response.status,200);return response.json()};
 const {alpha}=await control({op:'heavy',messages:1,otherMessages:1,chars:50,nodes:0});
 await control({op:'patch',sessions:{[alpha]:{messages:[{id:'user',role:'user',text:'Saved question',createdAt:1791582200}]}}});
 vite=await createServer({configFile:false,root:root+'frontend',server:{host:'127.0.0.1',port:0,hmr:false,proxy:{'/api':{target,changeOrigin:true,configure(proxy){proxy.on('proxyReq',request=>request.setHeader('Origin',target))}},'/branding':target}}});await vite.listen();
 browser=await chromium.launch({headless:true,args:process.env.CHROMIUM_SINGLE_PROCESS==='1'?['--single-process','--no-zygote']:[]});const page=await browser.newPage({viewport:{width:1280,height:900},extraHTTPHeaders:headers});page.on('pageerror',e=>errors.push(e.message));
 page.on('request',request=>{if(request.url().endsWith('/api/actions')&&request.method()==='POST')calls.push(request.postDataJSON())});
 await page.goto(vite.resolvedUrls.local[0]);
 await control({op:'patch',sessions:{[alpha]:{status:'error',error:'Saved worker message',errorAt:1791582278,failure:{category:'unknown',errorType:'str',summary:'Legacy summary',guidance:'A recovery copy can help',recordedAt:1791582278}}}});
 await page.reload();
 await page.getByRole('button',{name:'View error details',exact:true}).click();
 const panel=page.getByRole('dialog');
 await expect(panel.getByRole('heading',{name:'Error details',exact:true})).toBeVisible();
 await expect(panel).toContainText('Something interrupted this chat.');
 await expect(panel).not.toContainText('Recorded error: str');
 await expect(panel).not.toContainText('Conversation usage');
 await expect(panel).not.toContainText('recovery copy');
 await expect(panel.getByText(alpha,{exact:true})).toBeVisible();
 await expect(panel.getByText('Saved worker message',{exact:true})).not.toBeVisible();
 await panel.getByText('Technical details',{exact:true}).click();
 await expect(panel.getByText('Saved worker message',{exact:true})).toBeVisible();
 assert.equal(calls.filter(call=>call.action==='session.inspect').length,0,'Opening error details must not scan history');
 await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.copiedDiagnostic=text}}}));
 await panel.getByRole('button',{name:'Copy diagnostics',exact:true}).click();
 await expect(panel.getByRole('status')).toHaveText('Diagnostics copied');
 const copied=await page.evaluate(()=>JSON.parse(window.copiedDiagnostic));
 assert.equal(copied.sessionId,alpha);assert.equal(copied.failure.category,'unknown');
 await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw Error('Denied')}}}));
 await panel.getByRole('button',{name:'Copy diagnostics',exact:true}).click();
 await expect(panel.getByRole('alert')).toContainText('Clipboard unavailable');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'/tmp/unified-error-details-mobile.png'});
 await page.setViewportSize({width:1280,height:900});
 await panel.getByText('Technical details',{exact:true}).click();
 await page.screenshot({path:'/tmp/unified-error-details.png'});
 await control({op:'patch',sessions:{[alpha]:{status:'idle',error:null,failure:null}}});
 await expect(panel).toContainText('No current error is recorded for this chat.');
 const effects=calls.filter(call=>['conversation.send','session.recover'].includes(call.action));
 assert.deepEqual(effects,[],'Inspecting a failure must not replay work');
 assert.deepEqual(errors,[]);
 console.log('Focused error details passed: legacy failure, reload, explicit diagnostics, clipboard denial, mobile, and no replay.');
}finally{await browser?.close();await vite?.close();fixture.kill('SIGTERM')}
