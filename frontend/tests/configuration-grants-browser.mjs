import './composer-test-helpers.mjs';
import {showFixtureConversation,openChatAdvancedPage} from './browser-chat-pages.mjs';
import {spawn} from 'node:child_process';
import {mkdir,mkdtemp,writeFile} from 'node:fs/promises';
import {join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';

const root=process.env.AMPLIFIER_TEST_ROOT||fileURLToPath(new URL('../../',import.meta.url));
const python=process.env.AMPLIFIER_TEST_PYTHON||root+'/.venv/bin/python';
const base=resolve(process.env.AMPLIFIER_TEST_OUTPUT_DIR||join(root,'working-files'));
await mkdir(base,{recursive:true});
const output=await mkdtemp(join(base,'configuration-grants-browser-'));
const fixture=spawn(python,[root+'/tests/fixtures/coordination_ui_server.py'],{stdio:['ignore','pipe','inherit'],env:{...process.env,AMPLIFIER_TEST_OUTPUT_DIR:output}});
let browser,page;
try{
 const url=await new Promise((resolve,reject)=>{let output='';const timeout=setTimeout(()=>reject(Error('startup')),15000);fixture.stdout.on('data',chunk=>{output+=chunk;for(const line of output.split('\n'))try{const row=JSON.parse(line);if(row.url){clearTimeout(timeout);resolve(row.url)}}catch{}});fixture.once('error',reject)});
 browser=await chromium.launch({headless:true});
 page=await browser.newPage({viewport:{width:1100,height:900},extraHTTPHeaders:{Authorization:'Bearer fixture-browser-control-token'}});
 page.setDefaultTimeout(10000);
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(url);
 await showFixtureConversation(page);
 await page.evaluate(()=>window.amplifier.dispatch('view.update',{patch:{panel:null}}));
 const composer=page.getByRole('textbox',{name:'Message Amplifier'});
 await composer.fill('Configure the requested local file access');
 await page.getByRole('button',{name:'Send message',exact:true}).click();
 const inspect=()=>page.request.get(url+'/fixture').then(r=>r.json());
 const current=await inspect();
 await expect.poll(async()=>(await inspect()).contexts[current.selected]?.active).toBe(true);
 await composer.fill('Retain this private unfinished draft');
 const call=(action,args,id)=>page.request.post(url+'/fixture/peer',{data:{actor:'source',action,args,id}});
 const save={scope:'local',allowed:[],denied:[]};
 assert.equal((await call('permissions.save',save,'ungranted')).status(),403);
 let response=await call('capability.request',{sessionId:current.selected,effects:['file_access'],scopes:['local'],reason:'Adjust the local file access requested for this task'},'request');
 assert.equal(response.status(),200,await response.text());
 const grant=(await response.json()).result;
 const approval=page.locator(`[data-approval-id="${grant.id}"]`);
 await expect(approval.getByText('Allow configuration changes?',{exact:true})).toBeVisible();
 await expect(approval).toContainText('This conversation only');
 await approval.getByRole('button',{name:'Allow',exact:true}).click();
 await expect(approval).toHaveCount(0);
 for(const id of ['allowed-first','allowed-second']){
  response=await call('permissions.save',save,id);
  assert.equal(response.status(),200,await response.text());
  await expect.poll(async()=>(await inspect()).managementResults?.[id]?.phase).toBe('ready');
 }
 assert.equal((await inspect()).approvalResponses.length,0,'host-owned approval must not masquerade as native approval');
 await expect(composer).toHaveDraft('Retain this private unfinished draft');
 await page.reload();
 await expect(composer).toHaveDraft('Retain this private unfinished draft');
 await openChatAdvancedPage(page,'Model & tools');
 const controls=page.getByRole('region',{name:'Configuration permissions'});
 await controls.getByText('Agent permissions for settings',{exact:true}).click();
 await controls.getByRole('button',{name:'Refresh permissions',exact:true}).click();
 const row=controls.locator(`[data-grant-id="${grant.id}"]`);
 await expect(row).toContainText('Allowed');
 await page.screenshot({path:join(output,'desktop.png'),animations:'disabled'});
 await row.getByRole('button',{name:'Revoke permission',exact:true}).click();
 await expect(row).toContainText('revoked');
 assert.equal((await call('permissions.save',save,'after-revoke')).status(),403);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await controls.evaluate(element=>element.scrollWidth<=element.clientWidth),true);
 await page.screenshot({path:join(output,'mobile.png'),animations:'disabled'});
 await page.getByRole('button',{name:'Close panel',exact:true}).click();
 await expect(composer).toHaveDraft('Retain this private unfinished draft');
 assert.equal(await page.evaluate(()=>window.amplifier.getState().selectedSessionId),current.selected);
 assert.deepEqual(errors,[]);
 const report={passed:true,hostApproval:true,reusableAuthority:true,revocation:true,reload:true,privateDraft:true,mobile:true,scriptedRuntime:true,realProvider:false};
 await writeFile(join(output,'report.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify({output,...report}));
}finally{await browser?.close();fixture.kill('SIGTERM')}
