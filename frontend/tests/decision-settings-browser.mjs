// Live settings acceptance against the owned preview; reuses its existing Jev key.
import {chromium,expect} from '@playwright/test';
import {readFileSync,writeFileSync,mkdtempSync,rmSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {openSettingsPage} from './browser-settings.mjs';
assert.equal(execFileSync('hostname',{encoding:'utf8'}).trim(),'dtu-unified-device-connect-20261020');
const base='/var/lib/device-connect',origin='https://127.0.0.1:8961';
const access=JSON.parse(readFileSync(base+'/access.json'));
const profile=mkdtempSync(base+'/browser/decision-settings-');
const context=await chromium.launchPersistentContext(profile,{headless:true,args:['--no-sandbox','--single-process','--no-zygote','--disable-gpu'],viewport:{width:1500,height:1000}});
const page=await context.newPage(),errors=[],requests=[],report={checks:[]};
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>{if(request.url().endsWith('/api/actions')&&request.method()==='POST'){const data=request.postDataJSON();requests.push({action:data.action,id:data.args?.id})}});
const pass=name=>{report.checks.push(name);console.log('PASS '+name)};
try{
 await page.goto(origin+'/');
 if(page.url().includes('/login')){await page.locator('input[name=username]').fill(access.username);await page.locator('input[name=password]').fill(access.password);await page.locator('button[type=submit]').click()}
 await page.getByRole('button',{name:'Close panel',exact:true}).click().catch(()=>{});
 await page.waitForFunction(()=>window.amplifier?.dispatch);
 const review=JSON.parse(readFileSync(base+'/evidence/live-'+(process.env.UI_USE_REVIEW_CASE||'natural-browser-chat')+'.json'));
 await page.evaluate(id=>window.amplifier.dispatch('session.select',{id}),review.sessionId);
 await page.getByRole('button',{name:'Browser & computer',exact:true}).waitFor();
 await openSettingsPage(page,'ai-connections');
 const settings=page.locator('[data-part="ai-connections"]');
 await page.waitForFunction(()=>window.amplifier.getState().setup.decisionModels?.services?.length>0);
 await settings.locator('.a-everyday-list button').filter({hasText:'Jev'}).click();
 await settings.getByRole('button',{name:'Choose decision preferences',exact:true}).waitFor();
 assert.equal(await settings.getByRole('button',{name:'Choose model',exact:true}).count(),0);
 pass('Decision-only connection offers decision preferences instead of a chat model');
 await settings.getByText('Account and connection checks',{exact:true}).click();
 await settings.getByRole('button',{name:'Change credentials',exact:true}).click();
 await settings.getByLabel('Use the key already on this host',{exact:false}).check();
 await settings.getByRole('button',{name:'Save connection',exact:true}).click();
 const panel=settings.locator('[data-part="decision-model-settings"]');
 await panel.getByLabel('Use for',{exact:true}).waitFor();
 pass('Existing host credential is reused without entering a key or requesting a chat catalog');
 await panel.getByLabel('Use for',{exact:true}).selectOption('browser');
 await panel.getByLabel('Action selection',{exact:true}).selectOption('standard');
 await panel.getByRole('button',{name:'Save selection',exact:true}).click();
 await panel.getByText('Saved for new conversations. Applies to bundles with UI use enabled.',{exact:true}).waitFor();
 await page.waitForFunction(()=>window.amplifier.getState().setup.decisionModels.selection.browser.mode==='standard');
 pass('Ordinary model selection saves through the actual configuration service');
 await panel.getByLabel('Action selection',{exact:true}).selectOption('decision');
 const identity=await panel.getByLabel('Provider connection',{exact:true}).locator('option').evaluateAll(rows=>rows.find(row=>row.textContent.includes('Jev'))?.value);
 assert.ok(identity);await panel.getByLabel('Provider connection',{exact:true}).selectOption(identity);
 await panel.getByLabel('Allow observations from the browser to be sent to this decision service',{exact:true}).check();
 await panel.getByRole('button',{name:'Save selection',exact:true}).click();
 await panel.getByText('Saved for new conversations. Applies to bundles with UI use enabled.',{exact:true}).waitFor();
 await page.waitForFunction(()=>window.amplifier.getState().setup.decisionModels.selection.browser.mode==='decision');
 const state=await page.evaluate(()=>{const data=window.amplifier.getState().setup.decisionModels;return {selection:data.selection,backends:data.backends}});
 assert.equal(state.backends[state.selection.browser.backend].provider,identity);
 assert.equal(state.backends[state.selection.browser.backend].model,'jev-1.14.0');
 pass('Explicit Jev choice and observation consent save for new chats');
 await page.screenshot({path:base+'/evidence/ui-decision-settings.png'});
 await settings.getByRole('button',{name:'Back',exact:true}).click();
 await settings.getByRole('button',{name:'Connect another service',exact:true}).click();
 await settings.locator('.a-everyday-list button').filter({hasText:'Local decisions'}).click();
 await settings.getByLabel('API base URL',{exact:true}).waitFor();
 await expect(settings.getByRole('button',{name:'Save connection',exact:true})).toBeDisabled();
 await settings.getByText('The decision service must already be running at an address reachable from the Amplifier host. Use its full decision endpoint.',{exact:true}).waitFor();
 pass('Installed local adapter offers endpoint and token setup without claiming inference is installed');
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 assert.equal(errors.length,0,errors.join('\n'));
 assert.ok(!requests.some(row=>row.action==='providers.models'&&row.id===identity));
 pass('Mobile settings fit; no JavaScript errors or decision-provider chat catalog request');
 report.passed=true;
}finally{
 await page.screenshot({path:base+'/evidence/ui-decision-settings-last.png'}).catch(()=>{});
 report.requests=requests;report.errors=errors;
 writeFileSync(base+'/evidence/ui-decision-settings-browser.json',JSON.stringify(report,null,2));
 await context.close();rmSync(profile,{recursive:true,force:true});
}
