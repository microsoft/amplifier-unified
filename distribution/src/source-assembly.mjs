// Publisher-side assembly only. Inputs are independently reviewed expectations,
// never observations promoted to authority. Native/Foundation retain policy.
import {constants} from 'node:fs';
import {open, realpath, lstat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {isAbsolute, resolve, join, relative} from 'node:path';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {verifyPythonRuntime, resolveNativeSourceResolution} from './release-runtime.mjs';

const fail = code => {throw Error(code);};
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const sha = value => typeof value === 'string' && /^[a-f0-9]{64}$/.test(value);
const object = value => value && typeof value === 'object' && !Array.isArray(value);
const exact = (value, fields) => {
  if (!object(value) || Object.keys(value).sort().join(',') !== [...fields].sort().join(',')) fail('source_assembly_input_invalid');
};
const absolute = value => {
  if (typeof value !== 'string' || value.length > 4096 || !isAbsolute(value) || resolve(value) !== value || /[\\\x00-\x1f\x7f]/.test(value)) fail('source_assembly_path_invalid');
  return value;
};
const fileName = value => {
  if (typeof value !== 'string' || !value || value.length > 1024 || isAbsolute(value) ||
      /[\\\x00-\x1f\x7f]/.test(value) || value.split('/').some(p => !p || p === '.' || p === '..')) fail('source_assembly_path_invalid');
  return value;
};
// Canonical roots and member names are already validated. Nested roots may
// still name the same physical file; Native row spelling is not its identity.
const key = (root, name) => join(root, name);
const representation = entry => JSON.stringify([entry.sourceRoot,entry.path]);
const put = (map, root, name, digest) => {
  absolute(root); fileName(name);
  if (!sha(digest)) fail('source_assembly_digest_invalid');
  const id = key(root, name), previous = map.get(id);
  if (previous && previous.sha256 !== digest) fail('source_assembly_expected_digest_conflict');
  const entry = {sourceRoot:root, path:name, sha256:digest};
  // Pick a stable original spelling independent of row/materialization order.
  if (!previous || representation(entry) < representation(previous)) map.set(id,entry);
};

/** Pure projection into Native's existing v1 schema. An artifact's materialized
 * ReleaseFile entries must be independently reviewed with its existing archive
 * identity, not generated by hashing the destination. This first bounded repair
 * changes digests only; added/removed row membership requires a separately
 * reviewed source manifest. No URI, revision, approval or attribution is inferred.
 */
export function assembleSourceResolutionManifest({manifest, reviewedArtifacts = []}) {
  exact(manifest, ['version','sources']);
  if (manifest.version !== 1 || !Array.isArray(manifest.sources) || !manifest.sources.length || manifest.sources.length > 512) fail('source_assembly_input_invalid');
  const inventory = new Map(), bindings = new Set(), packages = new Map(); let count = 0;
  for (const row of manifest.sources) {
    exact(row, ['requestedUri','basePath','activePath','sourceRoot','resolvedCommit','approval','files','admissionFiles','packages']);
    if (typeof row.requestedUri !== 'string' || !row.requestedUri || row.requestedUri.length > 4096 || /[\x00-\x1f\x7f?]/.test(row.requestedUri)) fail('source_assembly_input_invalid');
    const raw = row.requestedUri.replace(/^git\+/, '');
    if (/^[a-zA-Z][a-zA-Z0-9+.-]*:/.test(raw) || raw.startsWith('//')) {
      let uri; try {uri = new URL(raw.startsWith('//') ? 'https:'+raw : raw);} catch {fail('source_assembly_input_invalid');}
      if (uri.username || uri.password || uri.search) fail('source_assembly_input_invalid');
    }
    absolute(row.sourceRoot); absolute(row.activePath);
    const part = relative(row.sourceRoot, row.activePath);
    if (part === '..' || part.startsWith('../') || isAbsolute(part)) fail('source_assembly_path_invalid');
    if (row.basePath !== null) absolute(row.basePath);
    if (row.resolvedCommit !== null && (typeof row.resolvedCommit !== 'string' || !/^([a-f0-9]{40}|[a-f0-9]{64})$/.test(row.resolvedCommit))) fail('source_assembly_input_invalid');
    if (row.requestedUri.startsWith('git+') && row.resolvedCommit === null) fail('source_assembly_input_invalid');
    if (row.approval !== null && (typeof row.approval !== 'string' || !row.approval || row.approval.length > 512 || /[\x00-\x1f\x7f]/.test(row.approval))) fail('source_assembly_input_invalid');
    const binding = JSON.stringify([row.requestedUri,row.basePath]);
    if (bindings.has(binding)) fail('source_assembly_binding_duplicate');
    bindings.add(binding);
    if (!object(row.files) || !Object.keys(row.files).length || (count += Object.keys(row.files).length) > 65536) fail('source_assembly_input_invalid');
    for (const [name, digest] of Object.entries(row.files)) put(inventory, row.sourceRoot, name, digest);
    if (!Array.isArray(row.admissionFiles) || !row.admissionFiles.length || row.admissionFiles.length > 128 || row.admissionFiles.some(name => !Object.hasOwn(row.files,name))) fail('source_assembly_input_invalid');
    if (!Array.isArray(row.packages) || row.packages.length > 128 || row.packages.some(name => typeof name !== 'string' || !/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name))) fail('source_assembly_input_invalid');
    for (const name of row.packages) {
      // Native discovers actual import specs and verifies their exact origins.
      // A filename heuristic cannot establish activation or importability.
      if (packages.has(name) && packages.get(name) !== row.sourceRoot) fail('source_assembly_input_invalid');
      packages.set(name,row.sourceRoot);
    }
  }
  // Reject contradictions in the original declarations BEFORE any replacement.
  // An approved artifact must not erase evidence of a contradictory donor row.
  if (!Array.isArray(reviewedArtifacts) || reviewedArtifacts.length > 128) fail('source_assembly_input_invalid');
  const replacements = new Map();
  let replacementCount = 0;
  const metadata = new Map();
  for (const reviewed of reviewedArtifacts) {
    exact(reviewed,['artifact','materialization']);
    const {artifact, materialization} = reviewed;
    if (!object(artifact) || !sha(artifact.sha256) || typeof artifact.revision !== 'string' || !/^([a-f0-9]{40}|[a-f0-9]{64})$/.test(artifact.revision)) fail('source_assembly_input_invalid');
    absolute(artifact.path);
    exact(materialization, ['sourceRoot','files','members']); absolute(materialization.sourceRoot);
    if (!Array.isArray(materialization.files) || !materialization.files.length || (replacementCount += materialization.files.length) > 65536) fail('source_assembly_input_invalid');
    if (!object(materialization.members) || Object.keys(materialization.members).length !== materialization.files.length) fail('source_assembly_input_invalid');
    for (const entry of materialization.files) {
      exact(entry, ['path','sha256','bytes','mode']);
      if (!Number.isSafeInteger(entry.bytes) || entry.bytes < 0 || entry.bytes > 64*1024*1024 || ![420,493].includes(entry.mode)) fail('source_assembly_input_invalid');
      put(replacements, materialization.sourceRoot, entry.path, entry.sha256);
      if (!Object.hasOwn(materialization.members,entry.path)) fail('source_assembly_input_invalid');
      fileName(materialization.members[entry.path]);
      const id = key(materialization.sourceRoot,entry.path), previous = metadata.get(id);
      if (previous && (previous.bytes !== entry.bytes || previous.mode !== entry.mode)) fail('source_assembly_expected_digest_conflict');
      metadata.set(id,entry);
      if (!inventory.has(key(materialization.sourceRoot,entry.path))) fail('source_assembly_membership_change_requires_review');
    }
  }
  for (const [id, entry] of replacements) inventory.set(id,{...inventory.get(id),sha256:entry.sha256});
  const document = structuredClone(manifest);
  for (const row of document.sources) for (const name of Object.keys(row.files)) row.files[name] = inventory.get(key(row.sourceRoot,name)).sha256;
  if (Buffer.byteLength(JSON.stringify(document)) > 16*1024*1024) fail('source_assembly_input_invalid');
  return {manifest:document, inventory:[...inventory.values()].sort((a,b) => key(a.sourceRoot,a.path) < key(b.sourceRoot,b.path) ? -1 : key(a.sourceRoot,a.path) > key(b.sourceRoot,b.path) ? 1 : 0)};
}

async function readRegular(path, limit = 64*1024*1024) {
  absolute(path);
  if (await realpath(path) !== path) fail('source_assembly_path_invalid');
  const fd = await open(path,constants.O_RDONLY|constants.O_NOFOLLOW|constants.O_NONBLOCK);
  try {
    const before = await fd.stat();
    if (!before.isFile() || before.size > limit || before.mode & 0o022) fail('source_assembly_file_invalid');
    const bytes = await fd.readFile(), after = await fd.stat();
    if (bytes.length > limit || before.size !== after.size || before.mtimeMs !== after.mtimeMs || before.ctimeMs !== after.ctimeMs) fail('source_assembly_file_changed');
    return {bytes, mode:before.mode & 0o777};
  } finally {await fd.close();}
}

/** Verify destinations against the trusted plan, never refresh expectations. */
export async function verifySourceAssembly(input) {
  const result = assembleSourceResolutionManifest(input);
  if (input.reviewedArtifacts?.length) {
    const runtime=input.ownerRuntime, python=input.native?.command;
    const selected=runtime?.trees?.find(tree => tree.id===runtime.python?.tree);
    if (!selected || join(selected.root,runtime.python.path)!==python) fail('source_assembly_native_invalid');
    const executable=await realpath(python), tree=runtime.trees.find(tree => {
      const path=relative(tree.root,executable);return path && path!=='..' && !path.startsWith('../') && !isAbsolute(path);
    });
    const expected=tree?.entries.find(entry => entry.path===relative(tree.root,executable));
    if (expected?.kind!=='file' || !sha(expected.sha256)) fail('source_assembly_native_invalid');
    const actual=await readRegular(executable);
    if(hash(actual.bytes)!==expected.sha256 || actual.bytes.length!==expected.bytes || actual.mode!==expected.mode) fail('source_assembly_parser_executable_drift');
  }
  // All wheel provenance checks finish before comparing any destination. The
  // existing admitted Python executes only the source-side stdlib checker.
  for (const {artifact, materialization} of input.reviewedArtifacts ?? []) {
    const archive = (await readRegular(artifact.path,64*1024*1024)).bytes;
    if (hash(archive) !== artifact.sha256) fail('source_assembly_artifact_drift');
    await verifyWheelMembers(input.native?.command,archive,artifact.sha256,materialization);
  }
  for (const {materialization} of input.reviewedArtifacts ?? []) {
    for (const entry of materialization.files) {
      const actual = await readRegular(join(materialization.sourceRoot,entry.path));
      if (actual.bytes.length !== entry.bytes || actual.mode !== entry.mode || hash(actual.bytes) !== entry.sha256) fail('source_assembly_observed_drift');
    }
  }
  for (const row of result.manifest.sources) {
    for (const path of [row.sourceRoot,row.activePath,...(row.basePath === null ? [] : [row.basePath])]) {
      if (await realpath(path) !== path) fail('source_assembly_path_invalid');
    }
    if (!(await lstat(row.sourceRoot)).isDirectory()) fail('source_assembly_path_invalid');
  }
  for (const entry of result.inventory) if (hash((await readRegular(join(entry.sourceRoot,entry.path))).bytes) !== entry.sha256) fail('source_assembly_observed_drift');
  return result;
}

function verifyWheelMembers(python, archive, sha256, materialization) {
  absolute(python);
  return new Promise((accept,reject) => {
    const child = spawn(python,['-I','-B','-S',fileURLToPath(new URL('./wheel-materialization.py',import.meta.url))],{env:{},stdio:'pipe'});
    let output='',stderrBytes=0,failed=false;
    const timer=setTimeout(() => {failed=true;child.kill('SIGKILL');},20000);
    child.on('error',() => {failed=true;}); child.stdin.on('error',() => {failed=true;});
    child.stdout.on('data',bytes => {output+=bytes;if(output.length>1024){failed=true;child.kill('SIGKILL');}});
    child.stderr.on('data',bytes => {stderrBytes+=bytes.length;if(stderrBytes>65536){failed=true;child.kill('SIGKILL');}});
    child.on('close',(code,signal) => {
      clearTimeout(timer);let result;try{result=JSON.parse(output);}catch{failed=true;}
      if (failed || code!==0 || signal || stderrBytes || result?.verifiedFiles!==materialization.files.length) reject(Error('source_assembly_wheel_provenance_invalid'));
      else accept();
    });
    const header=JSON.stringify({sha256,files:materialization.files,members:materialization.members})+'\n';
    if(Buffer.byteLength(header)>16*1024*1024){failed=true;child.kill('SIGKILL');return;}
    child.stdin.write(header); child.stdin.end(archive);
  });
}

/** Only one initialize request, then EOF and confirmed exit. The trusted caller
 * supplies the exact final engine/environment; nothing is inherited or rewritten.
 * This does not create a session, invoke a model, or advertise runtime readiness.
 */
export function initializeOnly(native, {timeoutMs = 20000} = {}) {
  exact(native, ['command','args','cwd','env','initialize']);
  absolute(native.command); absolute(native.cwd);
  if (!Array.isArray(native.args) || native.args.length !== 6 || native.args.slice(0,5).join('\0') !== ['-I','-B','-m','amplifier_acp','--config'].join('\0') || !object(native.env) || Object.values(native.env).some(v => typeof v !== 'string') || !object(native.initialize) || native.initialize.protocolVersion !== 1 || !Number.isInteger(timeoutMs) || timeoutMs < 1 || timeoutMs > 60000) fail('source_assembly_native_invalid');
  absolute(native.args[5]);
  return new Promise((accept, reject) => {
    const child = spawn(native.command,native.args,{cwd:native.cwd,env:native.env,stdio:'pipe'});
    let output = '', stdoutBytes = 0, stderrBytes = 0, response, failure, finished = false;
    const refuse = code => {failure ??= Error(code); child.kill('SIGKILL');};
    const timer = setTimeout(() => refuse('source_assembly_initialize_timeout'),timeoutMs);
    child.once('error', () => {failure ??= Error('source_assembly_initialize_spawn_failed');});
    child.stdin.on('error', () => {failure ??= Error('source_assembly_initialize_io_failed');});
    child.stderr.on('data', bytes => {stderrBytes += bytes.length; if (stderrBytes > 65536) refuse('source_assembly_initialize_output_limit');});
    child.stdout.on('data', bytes => {
      stdoutBytes += bytes.length;
      if (stdoutBytes > 1024*1024) {refuse('source_assembly_initialize_output_limit'); return;}
      output += bytes.toString('utf8');
      while (output.includes('\n')) {
        const end = output.indexOf('\n'), line = output.slice(0,end); output = output.slice(end+1);
        let row; try {row = JSON.parse(line);} catch {refuse('source_assembly_initialize_protocol_invalid'); return;}
        if (!object(row) || response || row.jsonrpc !== '2.0' || row.id !== 1 || row.error || row.result?.protocolVersion !== 1 || row.method) {refuse('source_assembly_initialize_protocol_invalid'); return;}
        response = row.result; child.stdin.end();
      }
    });
    child.once('close', (code,signal) => {
      if (finished) return; finished = true; clearTimeout(timer);
      if (failure) reject(failure);
      else if (code !== 0 || signal || !response || output || stderrBytes) reject(Error('source_assembly_initialize_failed'));
      else accept({protocolVersion:1, exitCode:0, signal:null, requests:['initialize'], stderrBytes:0});
    });
    child.stdin.write(JSON.stringify({jsonrpc:'2.0',id:1,method:'initialize',params:native.initialize})+'\n');
  });
}

/** Maintained staging gate. A verification result is returned only after the
 * sealed final runtime, final manifest/config and exact initialization agree.
 * Call before the existing staging READY promotion; never apply to a live tree.
 */
export async function verifySourceAssemblyBeforeReady(plan, options) {
  exact(plan, ['manifest','reviewedArtifacts','ownerRuntime','nativeConfiguration','native']);
  const assembled = await verifySourceAssembly(plan);
  const python = await verifyPythonRuntime(plan.ownerRuntime);
  if (plan.native.command !== python) fail('source_assembly_native_invalid');
  exact(plan.nativeConfiguration,['path','sha256']);
  if (plan.native.args[5] !== plan.nativeConfiguration.path || !sha(plan.nativeConfiguration.sha256)) fail('source_assembly_native_invalid');
  const configBytes = (await readRegular(plan.nativeConfiguration.path,1024*1024)).bytes;
  if (hash(configBytes) !== plan.nativeConfiguration.sha256) fail('source_assembly_native_configuration_drift');
  const configuration = JSON.parse(configBytes);
  if (configuration.runtimeImmutable !== true) fail('source_assembly_native_invalid');
  exact(configuration.sourceResolutionManifest, ['path','sha256']);
  const reference = configuration.sourceResolutionManifest;
  const finalBytes = (await readRegular(reference.path,16*1024*1024)).bytes;
  if (hash(finalBytes) !== reference.sha256 || JSON.stringify(JSON.parse(finalBytes)) !== JSON.stringify(assembled.manifest)) fail('source_assembly_final_manifest_drift');
  const tree = plan.ownerRuntime.trees.find(tree => {
    const path = relative(tree.root,reference.path); return path && path !== '..' && !path.startsWith('../') && !isAbsolute(path);
  });
  if (!tree) fail('source_assembly_path_invalid');
  await resolveNativeSourceResolution(plan.ownerRuntime,{manifest:{tree:tree.id,path:relative(tree.root,reference.path)},sha256:reference.sha256});
  const initialization = await initializeOnly(plan.native,options);
  // Detect a preflight that changed qualified bytes/config; do not reseal them.
  await verifySourceAssembly(plan); await verifyPythonRuntime(plan.ownerRuntime);
  if (!(await readRegular(reference.path,16*1024*1024)).bytes.equals(finalBytes) || !(await readRegular(plan.nativeConfiguration.path,1024*1024)).bytes.equals(configBytes)) fail('source_assembly_preflight_changed_inputs');
  return {...assembled, initialization};
}
