"""Retain and verify frontend build output for repairing committed assets.

This artifact is build output, never a release qualification receipt. Verification
matches every non-static tracked input and every generated byte. It does not run
code from the downloaded artifact. Apply replaces generated files in an inactive,
task-owned checkout; it never stages, commits or qualifies them for release.
"""
from __future__ import annotations

import argparse
from contextlib import contextmanager
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import stat
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
from historical_web_layout import environment_directories

STATIC = 'amplifier_web/static'
MAX_FILES = 10_000
MAX_BYTES = 128 * 1024 * 1024
MAX_MANIFEST_BYTES = 4 * 1024 * 1024


def git(root, *args):
    return subprocess.check_output(['git', *args], cwd=root, timeout=30)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def safe_path(name):
    path = PurePosixPath(name)
    if (not name or '\\' in name or path.is_absolute() or ':' in name
            or any(part in {'', '.', '..'} for part in name.split('/'))):
        raise ValueError('Invalid artifact path')
    return path


def regular_tree(folder, *, allow_empty=False):
    """Reject links and special files before reading any artifact bytes."""
    if not stat.S_ISDIR(folder.lstat().st_mode):
        raise ValueError('Build output must be a real directory')
    paths = []
    total = 0
    for parent, directories, files in os.walk(folder, followlinks=False):
        for name in directories:
            path = Path(parent) / name
            if not stat.S_ISDIR(path.lstat().st_mode):
                raise ValueError('Linked build directories are not supported')
        for name in files:
            path = Path(parent) / name
            info = path.lstat()
            if not stat.S_ISREG(info.st_mode):
                raise ValueError('Build output contains a link or special file')
            relative = path.relative_to(folder).as_posix()
            safe_path(relative)
            paths.append((relative, path))
            total += info.st_size
            if len(paths) > MAX_FILES or total > MAX_BYTES:
                raise ValueError('Build output exceeds the artifact size limit')
    if not paths and not allow_empty:
        raise ValueError('Build output is empty')
    return sorted(paths)


def source_identity(root):
    # Static files may have changed in the completed build. Everything else
    # must match HEAD, including build helpers, workflows and package versions.
    exclude = ':!amplifier_web/static'
    if any(row[:1] != b'H' for row in git(root, 'ls-files', '-v', '-z', '--', '.', exclude).split(b'\0') if row):
        raise ValueError('Source index flags hide build inputs; clear skip-worktree/assume-unchanged first')
    git(root, 'diff', '--exit-code', 'HEAD', '--', '.', exclude)
    if git(root, 'ls-files', '--others', '--exclude-standard', '-z', '--', '.', exclude):
        raise ValueError('Untracked source inputs; commit or remove them first')
    entries = []
    for row in git(root, 'ls-tree', '-r', '-z', '--full-tree', 'HEAD').split(b'\0'):
        if not row:
            continue
        metadata, name = row.split(b'\t', 1)
        if name == STATIC.encode() or name.startswith((STATIC + '/').encode()):
            continue
        # Object IDs and modes bind all tracked inputs without loading their
        # contents or exporting source, credentials, or local environment files.
        entries.append([metadata.decode('ascii'), name.decode('utf-8')])
    env_files = {}
    for folder in environment_directories(root):
        for path in sorted(folder.glob('.env*')):
            if path.is_symlink():
                raise ValueError('Linked environment input is not supported')
            if path.is_file():
                env_files[path.relative_to(root).as_posix()] = digest(path.read_bytes())
    return {'tracked': digest(json.dumps(entries, ensure_ascii=False).encode()),
            'envFiles': env_files}


def create(root, destination, env):
    root = root.resolve()
    if not (root / STATIC).resolve().is_relative_to(root):
        raise ValueError('Build output escapes the checkout')
    if destination.exists():
        raise ValueError('Artifact destination already exists')
    inputs = source_identity(root)
    files = regular_tree(root / STATIC)
    destination.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix='.frontend-build-', dir=destination.parent))
    try:
        assets = {}
        for name, source in files:
            data = source.read_bytes()
            target = staging / 'static' / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            assets[name] = {'sha256': digest(data), 'bytes': len(data)}
        manifest = {
            'schema': 1, 'kind': 'frontend-build-output', 'qualified': False,
            'source': inputs, 'commit': git(root, 'rev-parse', 'HEAD').decode().strip(),
            'assets': assets,
            'workflow': {key: env.get(key) for key in (
                'GITHUB_REPOSITORY', 'GITHUB_RUN_ID', 'GITHUB_RUN_ATTEMPT', 'GITHUB_SHA')},
        }
        # Reject source/build changes during capture rather than mixing builds.
        if source_identity(root) != inputs or {
            name: {'sha256': digest(path.read_bytes()), 'bytes': path.stat().st_size}
            for name, path in regular_tree(root / STATIC)
        } != assets:
            raise ValueError('Inputs or build output changed during capture')
        (staging / 'manifest.json').write_text(json.dumps(manifest, sort_keys=True, indent=2) + '\n')
        staging.rename(destination)
        return manifest
    finally:
        if staging.exists():
            shutil.rmtree(staging)


def verify(root, directory):
    if not stat.S_ISDIR(directory.lstat().st_mode):
        raise ValueError('Artifact must be a real directory')
    if {path.name for path in directory.iterdir()} != {'manifest.json', 'static'}:
        raise ValueError('Unexpected artifact contents')
    path = directory / 'manifest.json'
    if not stat.S_ISREG(path.lstat().st_mode) or path.stat().st_size > MAX_MANIFEST_BYTES:
        raise ValueError('Invalid artifact manifest')
    manifest = json.loads(path.read_text())
    if (not isinstance(manifest, dict) or manifest.get('schema') != 1
            or manifest.get('kind') != 'frontend-build-output'
            or manifest.get('qualified') is not False):
        raise ValueError('Unsupported build artifact')
    if manifest.get('source') != source_identity(root.resolve()):
        raise ValueError('Build source differs from this checkout; rebuild for the current inputs')
    assets = manifest.get('assets')
    if not isinstance(assets, dict) or not 0 < len(assets) <= MAX_FILES:
        raise ValueError('Invalid asset inventory')
    for name in assets:
        safe_path(name)
    observed = {name: {'sha256': digest(path.read_bytes()), 'bytes': path.stat().st_size}
                for name, path in regular_tree(directory / 'static')}
    if observed != assets:
        raise ValueError('Build output differs from its manifest')
    return manifest


def tree(folder):
    """Include empty directories: Git does not record them, but they are local work."""
    files = {name: {'sha256': digest(path.read_bytes()), 'bytes': path.stat().st_size}
             for name, path in regular_tree(folder, allow_empty=True)}
    directories = sorted((Path(parent) / name).relative_to(folder).as_posix()
                         for parent, names, _ in os.walk(folder) for name in names)
    return {'files': files, 'directories': directories}


def asset_tree(assets):
    directories = {parent.as_posix() for name in assets
                   for parent in PurePosixPath(name).parents if parent != PurePosixPath('.')}
    return {'files': assets, 'directories': sorted(directories)}


@contextmanager
def apply_lock(path):
    """One importer per checkout; OS releases the lock even after process death."""
    if path.is_symlink():
        raise ValueError('Linked apply lock is not supported')
    with path.open('a+b') as handle:
        if os.name == 'nt':
            import msvcrt
            if not path.stat().st_size:
                handle.write(b'\0'); handle.flush()
            handle.seek(0)
            msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        try:
            yield
        finally:
            if os.name == 'nt':
                handle.seek(0)
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            # Closing the descriptor releases flock. Keep the tiny lock file so
            # another invocation can never lock a different inode at this path.


def save_apply_state(recovery, state, phase):
    temporary = recovery / 'state.tmp'
    temporary.write_text(json.dumps({**state, 'phase': phase}, sort_keys=True) + '\n')
    temporary.replace(recovery / 'state.json')
    state['phase'] = phase


def check_apply_inputs(root, state):
    if (git(root, 'rev-parse', 'HEAD').decode().strip() != state['head']
            or digest(git(root, 'ls-files', '--stage', '-z', '--', STATIC)) != state['index']
            or source_identity(root) != state['manifest']['source']):
        raise ValueError('Checkout or index changed during apply; preserve and resolve local work')


def clean_static(root, before):
    if any(row[:1] != b'H' for row in git(root, 'ls-files', '-v', '-z', '--', STATIC).split(b'\0') if row):
        raise ValueError('Static index flags hide local work; clear skip-worktree/assume-unchanged first')
    git(root, 'diff', '--exit-code', 'HEAD', '--', STATIC)
    git(root, 'diff', '--cached', '--exit-code', 'HEAD', '--', STATIC)
    if (git(root, 'ls-files', '--others', '-z', '--', STATIC)
            or before['directories'] != asset_tree(before['files'])['directories']):
        raise ValueError('Local generated files or empty directories would be overwritten')


def prepare_apply(root, directory, recovery, state):
    target, new, old = root / STATIC, recovery / 'new', recovery / 'old'
    if old.exists() or tree(target) != state['before']:
        raise ValueError('Original generated files changed during preparation')
    # Only this disposable staging tree may be incomplete after an interruption.
    if new.exists():
        regular_tree(new, allow_empty=True)
        shutil.rmtree(new)
    new.mkdir()
    for name in state['manifest']['assets']:
        destination = new / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(directory / 'static' / name, destination)
    if tree(new) != asset_tree(state['manifest']['assets']):
        raise ValueError('Build output changed while preparing replacement')
    check_apply_inputs(root, state)
    if tree(target) != state['before']:
        raise ValueError('Original generated files changed during preparation')
    save_apply_state(recovery, state, 'prepared')


def replace_static(root, recovery, state):
    target, new, old = root / STATIC, recovery / 'new', recovery / 'old'
    wanted = asset_tree(state['manifest']['assets'])
    if not old.exists():
        if tree(target) != state['before'] or tree(new) != wanted:
            raise ValueError('Generated files changed before replacement')
        target.rename(old)
    if tree(old) != state['before']:
        raise ValueError('Saved original generated files changed')
    if not target.exists():
        if tree(new) != wanted:
            raise ValueError('Prepared replacement changed')
        new.rename(target)
    if new.exists() or tree(target) != wanted:
        raise ValueError('Replacement contains local changes; leaving recovery files intact')
    check_apply_inputs(root, state)
    save_apply_state(recovery, state, 'verified')


def finish_apply(root, recovery, state):
    if tree(root / STATIC) != asset_tree(state['manifest']['assets']):
        raise ValueError('Applied generated files changed; leaving recovery files intact')
    old = recovery / 'old'
    if old.exists():
        remaining = tree(old)
        before = state['before']
        if (any(before['files'].get(name) != value for name, value in remaining['files'].items())
                or not set(remaining['directories']) <= set(before['directories'])):
            raise ValueError('Saved original files changed; leaving recovery files intact')
        # A previous invocation may have stopped partway through this deletion.
        shutil.rmtree(old)
    (recovery / 'state.tmp').unlink(missing_ok=True)
    (recovery / 'state.json').unlink()
    recovery.rmdir()


def restore_original(root, recovery, state):
    """On an ordinary failure, restore only bytes still known to belong to us."""
    target, new, old = root / STATIC, recovery / 'new', recovery / 'old'
    if state['phase'] != 'prepared' or not old.exists() or tree(old) != state['before']:
        return
    check_apply_inputs(root, state)
    if target.exists():
        if new.exists() or tree(target) != asset_tree(state['manifest']['assets']):
            return
        target.rename(new)
    old.rename(target)


def apply(root, directory):
    root = root.resolve()
    target = root / STATIC
    recovery = Path(git(root, 'rev-parse', '--absolute-git-dir').decode().strip()) / 'frontend-build-apply'
    try:
        if target.parent.is_symlink() or target.is_symlink() or recovery.is_symlink():
            raise ValueError('Linked target or recovery directory is not supported')
        if recovery.parent.stat().st_dev != target.parent.stat().st_dev:
            raise ValueError('Apply requires checkout and Git metadata on the same filesystem')
        if any(directory.resolve().is_relative_to(path) for path in (target, recovery)):
            raise ValueError('Artifact overlaps generated output or recovery directory')
        manifest = verify(root, directory)
        with apply_lock(recovery.with_suffix('.lock')):
            return apply_locked(root, directory, recovery, manifest)
    except Exception as error:
        error.add_note(f'Apply recovery: {recovery}. Preserve local work; rerun apply with the same artifact after resolving conflicts.')
        raise


def apply_locked(root, directory, recovery, manifest):
    wanted = asset_tree(manifest['assets'])
    # No record means replacement never began (possibly interrupted record write).
    if recovery.exists() and not (recovery / 'state.json').exists():
        if any(path.name != 'state.tmp' or not path.is_file() or path.is_symlink()
               for path in recovery.iterdir()):
            raise ValueError('Unrecognized recovery contents; preserve for inspection')
        (recovery / 'state.tmp').unlink(missing_ok=True)
        recovery.rmdir()
    resumed = recovery.exists()
    if resumed:
        if any(path.name not in {'state.json', 'state.tmp', 'new', 'old'} or path.is_symlink()
               for path in recovery.iterdir()):
            raise ValueError('Unrecognized recovery contents; preserve for inspection')
        state = json.loads((recovery / 'state.json').read_text())
        if state['manifest'] != manifest or state['phase'] not in {'preparing', 'prepared', 'verified'}:
            raise ValueError('Pending apply belongs to a different artifact')
    else:
        before = tree(root / STATIC)
        if before == wanted:
            return manifest, {'status': 'unchanged', 'recovered': False}
        clean_static(root, before)
        state = {'manifest': manifest, 'before': before, 'phase': 'preparing',
                 'head': git(root, 'rev-parse', 'HEAD').decode().strip(),
                 'index': digest(git(root, 'ls-files', '--stage', '-z', '--', STATIC))}
        recovery.mkdir()
        save_apply_state(recovery, state, 'preparing')
    try:
        check_apply_inputs(root, state)
        if state['phase'] == 'preparing':
            prepare_apply(root, directory, recovery, state)
        if state['phase'] == 'prepared':
            replace_static(root, recovery, state)
        finish_apply(root, recovery, state)
    except Exception as error:
        try:
            restore_original(root, recovery, state)
        except Exception as restore_error:
            error.add_note(f'Original files remain in recovery: {restore_error}')
        raise
    before, after = state['before']['files'], manifest['assets']
    return manifest, {'status': 'applied', 'recovered': resumed,
                      'added': len(after.keys() - before.keys()),
                      'removed': len(before.keys() - after.keys()),
                      'changed': sum(before[name] != after[name] for name in before.keys() & after.keys())}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='action', required=True)
    sub.add_parser('create').add_argument('--destination', required=True, type=Path)
    sub.add_parser('verify').add_argument('--directory', required=True, type=Path)
    sub.add_parser('apply').add_argument('--directory', required=True, type=Path)
    args = parser.parse_args()
    application = {}
    if args.action == 'apply':
        manifest, summary = apply(Path.cwd(), args.directory)
        application = {'application': summary}
    else:
        manifest = (create(Path.cwd(), args.destination, os.environ) if args.action == 'create'
                    else verify(Path.cwd(), args.directory))
    print(json.dumps({'sourceAndAssetBytesMatch': True, 'qualified': False,
                      'workflowProvenanceVerified': False,
                      'commit': manifest['commit'], 'files': len(manifest['assets']),
                      'workflow': manifest['workflow'], **application}))


if __name__ == '__main__':
    main()
