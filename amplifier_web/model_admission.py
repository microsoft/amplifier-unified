"""Bounded host admission observations, separate from provider failure payloads."""
from __future__ import annotations

import copy
import time

from .collaboration import BINDING
from .model_admission_identity import input_id


class ModelAdmissionPaused(ValueError):
    """No new provider request was dispatched because host admission refused."""


class ModelAdmissionWaitExpired(TimeoutError):
    """The configured wait expired before a provider request was dispatched."""


ERROR_TYPES = {'paused': 'ValueError', 'wait_expired': 'TimeoutError'}


def binding(session, args):
    row = args.get('call') or {}
    active = session.get('collaborationGeneration') or {}
    native = session.get('runtimeSessionId') or session['id']
    generation = (BINDING.get() or {}).get('_generationId')
    inputs = active.get('inputIds') or []
    if (not generation or generation != active.get('id') or active.get('terminal')
            or row.get('rootSessionId') != native or row.get('sessionId') != native
            or row.get('lifecycle') == 'background' or row.get('purpose')
            or not isinstance(row.get('id'), str) or len(row['id']) > 200
            or not isinstance(generation, str) or len(generation) > 200
            or len(inputs) > 64 or any(not isinstance(value, str) or len(value) > 200 for value in inputs)
            or input_id(row) not in inputs):
        return None
    return {'generationId': generation, 'inputIds': list(inputs),
            'interruptionRevision': session.get('interruptionRevision', 0),
            'configurationRevision': session.get('configurationPendingRevision', 0)}


async def admit(service, session_id, args):
    from .capacity_wait import admit as wait
    async with service.lock:
        session = service._session(session_id)
        before = binding(session, args)
        previous = session.get('modelAdmission')
    result = await wait(service, session_id, args)
    if not before:
        return result
    if result.get('allowed'):
        if not previous:
            return result
        async with service.lock:
            session = service._session(session_id)
            observed = session.get('modelAdmission') or {}
            if (before == binding(session, args) and observed == previous
                    and observed.get('generationId') == before['generationId']):
                session.pop('modelAdmission', None)
                service._save_changes(sessions={session_id})
        return result
    if result.get('state') not in ERROR_TYPES:
        return result
    async with service.lock:
        session = service._session(session_id)
        if before != binding(session, args):
            return result  # A late observation cannot attach across Stop/input changes.
        row = args['call']
        tree = session.get('execution') or {}
        if any(item.get('id') == row['id'] for item in
               tree.get('nodes', []) + tree.get('retiredUsageNodes', [])):
            return result  # A duplicate admitted ID can have prior unknown effects.
        # Reasons are generated by host policy, never copied from SDK messages.
        session['modelAdmission'] = {**before, 'callId': row['id'],
            'state': result['state'], 'budgetRevision': result.get('budgetRevision'),
            'reasons': [reason[:500] for reason in result.get('reasons', [])[:8]
                        if isinstance(reason, str)],
            'recordedAt': time.time(), 'providerRequestSent': False}
        service._save_changes(sessions={session_id})
    return result


def failure(session, event):
    """Bind a known host block without reconstructing a private exception cause.

    Native loop failures normalize local subclasses to built-in types. Preserve
    that terminal metadata alongside the host observation; never infer a cause
    from arbitrary exception messages or older denied calls.
    """
    observed = session.get('modelAdmission') or {}
    active = session.get('collaborationGeneration') or {}
    if (event.get('error_category') != 'unknown'
            or event.get('error_type') != ERROR_TYPES.get(observed.get('state'))
            or not observed.get('generationId')
            or observed['generationId'] != event.get('generation_id')
            or active.get('id') != observed['generationId']
            or set(event.get('input_ids') or []) != set(observed.get('inputIds') or [])
            or set(active.get('inputIds') or []) != set(observed.get('inputIds') or [])
            or session.get('interruptionRevision', 0) != observed.get('interruptionRevision')
            or session.get('configurationPendingRevision', 0) != observed.get('configurationRevision')):
        return None
    expired = observed['state'] == 'wait_expired'
    return {'category': 'model_capacity_wait_expired' if expired else 'model_capacity',
            'errorType': event['error_type'], 'stage': 'model_admission',
            'summary': 'The wait for model capacity ended.' if expired else 'A model-call limit paused this work.',
            'guidance': ('No new model request was sent. Continue to check available capacity again.'
                         if expired else
                         ' '.join(observed['reasons']) + ' Review the saved limits and unresolved calls before continuing. '
                         'No new model request was sent; unresolved reservations remain held.'),
            'effects': 'not_rolled_back', 'replayed': False, 'retryable': expired,
            'terminalFailure': {key: event[key] for key in
                                ('error_type', 'error_category', 'error_stage', 'retryable') if key in event},
            'admission': {key: copy.deepcopy(observed[key]) for key in
                          ('callId', 'state', 'budgetRevision', 'reasons', 'recordedAt', 'providerRequestSent')}}
